let num1 = prompt("Digite o primeiro numero: ")
let num2 = prompt("Digite o segundo numero: ")

let soma= parseFloat(num1)+parseFloat(num2)
let sub = parseFloat(num1) - parseFloat(num2)
let prod= parseFloat(num1) * parseFloat(num2)
let divisao= parseFloat(num1) / parseFloat(num2)
let resto= parseFloat(num1) % parseFloat(num2)

alert("A soma dos numeros é: "+ soma )
alert("A subtração dos numeros é: "+ sub )
alert("O produto dos numeros é: "+ prod )
alert("A divisão dos numeros é: "+ divisao )
alert("O resto dos numeros é: "+ resto )